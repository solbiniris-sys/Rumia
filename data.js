const VAL = { '☁': 1, '♜': 3, '✦': 2, '▤': 2, '❀': 2, '⌂': 1, '✧': 1, '❂': 2 };
function dreamStat(g) {
  const n = {}; let C = 0, P = 0, LP = 0, score = 0;
  const nb = i => { const r = Math.floor(i / 8), c = i % 8, out = [];
    for (let dr = -1; dr <= 1; dr++) for (let dc = -1; dc <= 1; dc++) { if (!dr && !dc) continue;
      const rr = r + dr, cc = c + dc; if (rr >= 0 && rr < 6 && cc >= 0 && cc < 8) out.push(rr * 8 + cc); } return out; };
  g.forEach((v, i) => { if (!v) return; n[v] = (n[v] || 0) + 1; score += VAL[v] || 0;
    if (v === '♜') { C++; const q = nb(i), door = q.some(j => g[j] === '⌂'); if (door) { P++; if (q.some(j => g[j] === '✧')) LP++; } } });
  score += P * 2 + LP * 2;
  return { C, P, LP, n, score, pct: Math.min(100, Math.round(score * 100 / 70)), bad: C >= 5 && P < Math.ceil(C / 2) };
}
